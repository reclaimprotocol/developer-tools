export function canonicalInspection() {
	const results: {
		case: string
		outcome: string
		sha256?: string
		modelCalls: number
	}[] = []
	const valid = (name: string, value: unknown, expected: string) => {
		const actual = canonicalJson(value)
		assert.equal(actual, expected, name)
		assert.equal(sha256(actual), sha256(expected), name)
		results.push({
			case: name,
			outcome: 'matched-reference',
			sha256: sha256(actual),
			modelCalls: 0,
		})
	}

	for(const [hex, expected] of jcsNumberVectors) {
		valid(`rfc8785-${hex}`, Buffer.from(hex, 'hex').readDoubleBE(), expected)
	}

	valid(
		'recursive-order',
		{ z: [{ b: 1, a: 2 }], a: true },
		'{"a":true,"z":[{"a":2,"b":1}]}',
	)
	valid(
		'utf16-property-order',
		{ '\ufb33': 7, '😀': 6, '€': 5, ö: 4, '\u0080': 3, '1': 2, '\r': 1 },
		'{"\\r":1,"1":2,"\u0080":3,"ö":4,"€":5,"😀":6,"דּ":7}',
	)
	valid(
		'rfc8785-numbers',
		[333333333.33333329, 1e30, 4.5, 2e-3, 1e-27],
		'[333333333.3333333,1e+30,4.5,0.002,1e-27]',
	)
	valid(
		'escaping',
		{ text: '€$\u000f\nA\'B"\\\\"/' },
		String.raw`{"text":"€$\u000f\nA'B\"\\\\\"/"}`,
	)
	let invoked = false
	const invalid: [string, unknown][] = [
		['nan', NaN],
		['positive-infinity', Infinity],
		['negative-infinity', -Infinity],
		['unpaired-high', '\ud800'],
		['unpaired-low', '\udfff'],
		['unpaired-key', { ['\ud800']: 1 }],
		[
			'accessor',
			{
				get value() {
					invoked = true
					return 'forbidden'
				},
			},
		],
		['undefined', { a: undefined }],
		['sparse-array', Array(2)],
		['prototype-key', JSON.parse('{"__proto__":1}')],
		['date-object', new Date(0)],
		['bigint', 1n],
		['symbol-key', { [Symbol()]: 1 }],
	]
	for(const [name, value] of invalid) {
		assert.throws(() => canonicalJson(value), name)
		results.push({ case: name, outcome: 'rejected', modelCalls: 0 })
	}

	assert.equal(invoked, false)
	return results
}

export interface XmlFixture {
	name: string
	input: DocumentInput
	error?: string
	text?: string
}
export function xmlFixtures(): XmlFixture[] {
	const fixtures: XmlFixture[] = []
	const add = (
		name: string,
		bytes: Buffer,
		filename = 'synthetic.xml',
		error?: string,
		text?: string,
	) => {
		fixtures.push({
			name,
			input: {
				id: `attachment:${fixtures.length}`,
				filename,
				mimeType: 'application/octet-stream',
				bytes,
			},
			error,
			text,
		})
	}

	for(const encoding of ['utf-8', 'utf-16le', 'utf-16be']) {
		add(
			encoding,
			iconv.encode(
				`\uFEFF<?xml version="1.0" encoding="${encoding}"?><x>Income €1234</x>`,
				encoding,
			),
			'synthetic.xml',
			undefined,
			'Income €1234',
		)
		add(
			`${encoding}-dtd`,
			iconv.encode(
				`\uFEFF<?xml version="1.0" encoding="${encoding}"?><!DOCTYPE x [<!ENTITY secret SYSTEM "file:///host-secret">]><x>&secret;</x>`,
				encoding,
			),
			'synthetic.xml',
			'ATTACHMENT_FORMAT_INVALID',
		)
	}

	add(
		'declaration-only-encoding',
		Buffer.from(
			'<?xml version="1.0" encoding="UTF-16LE"?><x>1234</x>',
			'utf16le',
		),
		'synthetic.xml',
		undefined,
		'1234',
	)
	add(
		'comment-not-declaration',
		Buffer.from('<x><!-- <!DOCTYPE x> -->1234</x>'),
		'synthetic.xml',
		undefined,
		'1234',
	)
	add(
		'inconsistent-encoding',
		Buffer.from('\uFEFF<?xml version="1.0" encoding="UTF-16"?><x/>'),
		'synthetic.xml',
		'ATTACHMENT_TEXT_UNREADABLE',
	)
	add(
		'malformed-final-chunk',
		Buffer.from('<x>' + 'a'.repeat(4090) + '</wrong>'),
		'synthetic.xml',
		'ATTACHMENT_FORMAT_INVALID',
	)
	add(
		'unknown-entity',
		Buffer.from('<x>&custom;</x>'),
		'synthetic.xml',
		'ATTACHMENT_FORMAT_INVALID',
	)
	add(
		'sgml-declaration',
		Buffer.from('<!ENTITY x "1234"><x/>'),
		'synthetic.xml',
		'ATTACHMENT_FORMAT_INVALID',
	)
	const docx = unzipSync(docxDocument('Synthetic income 1234'))
	docx['word/document.xml'] = Uint8Array.from(
		iconv.encode(
			'\uFEFF<?xml version="1.0" encoding="UTF-16"?>' +
				Buffer.from(docx['word/document.xml']).toString(),
			'utf-16le',
		),
	)
	add(
		'utf16-docx',
		Buffer.from(zipSync(docx)),
		'synthetic.docx',
		undefined,
		'Synthetic income 1234\n\n',
	)
	const rels = unzipSync(docxDocument())
	rels['_rels/.rels'] = Uint8Array.from(
		iconv.encode(
			'\uFEFF<?xml version="1.0" encoding="UTF-16"?><!DOCTYPE x><x/>',
			'utf-16be',
		),
	)
	add(
		'utf16-relationship-dtd',
		Buffer.from(zipSync(rels)),
		'synthetic.docx',
		'ATTACHMENT_FORMAT_INVALID',
	)
	const xlsx = unzipSync(xlsxDocument())
	xlsx['xl/worksheets/sheet1.xml'] = Uint8Array.from(
		iconv.encode(
			'\uFEFF<?xml version="1.0" encoding="UTF-16"?>' +
				Buffer.from(xlsx['xl/worksheets/sheet1.xml']).toString(),
			'utf-16be',
		),
	)
	add('utf16-xlsx', Buffer.from(zipSync(xlsx)), 'synthetic.xlsx')
	for(const count of [100_000, 100_001]) {
		const sheet =
			'<s:worksheet xmlns:s="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><s:sheetData><s:row>' +
			'<s:c/>'.repeat(count) +
			'</s:row></s:sheetData></s:worksheet>'
		// A DOCX may also contain auxiliary worksheet parts. Guards must count
		// namespace-aware events before either document reader gets the archive.
		const archive = unzipSync(docxDocument('Synthetic namespace check'))
		archive['xl/worksheets/sheet1.xml'] = strToU8(sheet)
		add(
			`namespaced-cells-${count}`,
			Buffer.from(zipSync(archive)),
			'synthetic.docx',
			count > 100_000 ? 'ATTACHMENT_TEXT_TOO_LARGE' : undefined,
		)
	}

	const manySheets = unzipSync(docxDocument())
	for(let i = 0; i < 101; i++) {
		manySheets[`xl/worksheets/sheet${i}.xml`] = strToU8('<worksheet/>')
	}

	add(
		'sheet-limit',
		Buffer.from(zipSync(manySheets)),
		'synthetic.docx',
		'ATTACHMENT_TEXT_TOO_LARGE',
	)
	const expansion = Buffer.from(
		zipSync({
			...unzipSync(docxDocument()),
			'word/media/data.bin': new Uint8Array(65 * 1024 * 1024),
		}),
	)
	for(let i = 0; i + 28 < expansion.length; i++) {
		if(expansion.readUInt32LE(i) === 0x04034b50) {
			expansion.writeUInt32LE(0, i + 22)
		}

		if(expansion.readUInt32LE(i) === 0x02014b50) {
			expansion.writeUInt32LE(0, i + 24)
		}
	}

	add(
		'actual-expansion-limit',
		expansion,
		'synthetic.docx',
		'ATTACHMENT_TEXT_TOO_LARGE',
	)
	return fixtures
}

export function xmlChunkInspection(size: number) {
	const results: { case: string, outcome: string, modelCalls: number }[] = []
	for(const encoding of ['utf-8', 'utf-16le', 'utf-16be']) {
		let cells = 0
		const guard = createXmlGuard({
			textChunkSize: 1,
			onOpenTag(node) {
				if(node.local === 'c' && node.uri === 'urn:test') {
					cells++
				}
			},
		})
		const data = iconv.encode(
			`\uFEFF<?xml version="1.0" encoding="${encoding}"?><s:row xmlns:s="urn:test"><s:c>é😀</s:c><s:c/></s:row>`,
			encoding,
		)
		for(let offset = 0; offset < data.length; offset += size) {
			guard.push(data.subarray(offset, offset + size))
		}

		assert(guard.push(Buffer.alloc(0), true)?.text.includes('é😀'))
		assert.equal(cells, 2)
		results.push({
			case: `${encoding}-${size}-byte-chunks`,
			outcome: 'passed',
			modelCalls: 0,
		})
		const bad = createXmlGuard({ textChunkSize: 1 })
		const bytes = iconv.encode(
			`\uFEFF<?xml version="1.0" encoding="${encoding}"?><!DOCTYPE x><x/>`,
			encoding,
		)
		assert.throws(() => {
			for(let offset = 0; offset < bytes.length; offset += size) {
				bad.push(bytes.subarray(offset, offset + size))
			}

			bad.push(Buffer.alloc(0), true)
		}, /ATTACHMENT_FORMAT_INVALID/)
		results.push({
			case: `${encoding}-${size}-byte-dtd`,
			outcome: 'rejected',
			modelCalls: 0,
		})
	}

	return results
}
