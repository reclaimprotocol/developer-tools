/* eslint-disable @stylistic/max-len -- ported from the email core's test suite; kept close to upstream so the two can be compared */
import { parseSignedDate } from '../../../src/email/lib/email/date.ts'
import { describe, expect, it } from './vitest-compat.ts'
// RFC 5322 sections 3.3, 3.2.2 and 4.3: required receiver interpretations.
it.each([
	['Sat, 26 Sep 2026 14:32:00 -0700', '2026-09-26T14:32:00-07:00'],
	['26 Sep 2026 14:32 +0530', '2026-09-26T14:32:00+05:30'],
	['26 Sep 2026 14:32:00 GMT', '2026-09-26T14:32:00+00:00'],
	['29 Feb 2024 00:00:00 +0000', '2024-02-29T00:00:00+00:00'],
	['Fri, 18 Sep 2026 15:51:56 -0000', '2026-09-18T15:51:56-00:00'],
	['Sat,26 Sep 2026 14:32:00 -0700', '2026-09-26T14:32:00-07:00'],
	['26 Sep 2026 14:32:00 +2400', '2026-09-26T14:32:00+24:00'],
	['26 Sep 2026 14:32:00 -9959', '2026-09-26T14:32:00-99:59'],
	['Thu, 31 Dec 1998 23:59:60 +0000', '1998-12-31T23:59:60+00:00'],
	['1 Jan 10000 00:00:00 +0000', '+010000-01-01T00:00:00+00:00'],
	[
		'Sat, 1 Jan 10000000000000000 00:00:00 +0000',
		'+10000000000000000-01-01T00:00:00+00:00',
	],
	['26 Sep 00002026 14:32:00 +0000', '2026-09-26T14:32:00+00:00'],
	[
		'(sent (by server)) Sat (weekday), (day)26 (month)Sep (year)2026 (hour)14 (h):(m)32 (m):(s)00 (zone) -0700 (end)',
		'2026-09-26T14:32:00-07:00',
	],
	[
		'26 Sep 2026 14:32:00 +0000 (escaped \\( and \\) and \\\\)',
		'2026-09-26T14:32:00+00:00',
	],
	['Sat,\r\n\t26 Sep 2026\r\n \t14:32:00 +0000', '2026-09-26T14:32:00+00:00'],
	['26 Sep 2026\r\n \r\n \t14:32:00 +0000', '2026-09-26T14:32:00+00:00'],
	['26 Sep 26 14:32:00 +0000', '2026-09-26T14:32:00+00:00'],
	['26 Sep 49 14:32:00 GMT', '2049-09-26T14:32:00+00:00'],
	['26 Sep 50 14:32:00 UT', '1950-09-26T14:32:00+00:00'],
	['26 Sep 99 14:32:00 EST', '1999-09-26T14:32:00-05:00'],
	['26 Sep 000 14:32:00 +0000', '1900-09-26T14:32:00+00:00'],
	['26 Sep 126 14:32:00 +0000', '2026-09-26T14:32:00+00:00'],
	['26Sep202614:32:00GMT', '2026-09-26T14:32:00+00:00'],
	['26 Sep 2026 14:32:00 A', '2026-09-26T14:32:00-00:00'],
	['26 Sep 2026 14:32:00 Z', '2026-09-26T14:32:00-00:00'],
	['26 Sep 2026 14:32:00 BST', '2026-09-26T14:32:00-00:00'],
	['26 Sep 2026 14:32:00 UTC', '2026-09-26T14:32:00+00:00'],
])('normalizes signed RFC date %s', (input, output) => {
	expect(parseSignedDate(input)).toBe(output)
})
it.each([
	'29 Feb 2026 00:00:00 +0000',
	'32 Sep 2026 00:00:00 +0000',
	'26 Sep 2026 00:00:00 +2460',
	'Fri, 26 Sep 2026 14:32:00 -0700',
	'2026-09-26',
	'26 Sep 1899 14:32:00 +0000',
	'26 Sep 0026 14:32:00 +0000',
	'0 Sep 2026 14:32:00 +0000',
	'29 Feb 1900 14:32:00 +0000',
	'26 Sep 2026 24:00:00 +0000',
	'26 Sep 2026 14:60:00 +0000',
	'26 Sep 2026 14:32:61 +0000',
	'26 Sep 2026 14:32:00 +0060',
	'26 Sep 2026 14:32:00 +9960',
	'26 Sep 2026 14:32:00 J',
	'26 Sep 2026 14:32:00 +00:00',
	'26 Sep 2026 14:32:00+0000',
	'26 Sep 2026 14:32:00(comment)+0000',
	'26 Sep 2026 14:32:00 + 0000',
	'26 Sep 2026 14:32:00 +0000 garbage',
	'26 Sep 2026 14:32:00 +0000 (unclosed',
	'26 Sep 2026 14:32:00 +0000 )',
	'26 Sep 2026 14:32:00 +0000 (dangling \\',
	'26 Sep 2026\n 14:32:00 +0000',
	'26 Sep 2026\r\n14:32:00 +0000',
	'26 Sep 2026\u00a014:32:00 +0000',
	'26 Sep 2026\x0014:32:00 +0000',
])('rejects invalid or ambiguous date %s', (input) => {
	expect(() => parseSignedDate(input)).toThrow('INVALID_DATE')
})

describe('obsolete alphabetic timezone interpretation', () => {
	it.each([
		['EDT', '-04:00'],
		['EST', '-05:00'],
		['CDT', '-05:00'],
		['CST', '-06:00'],
		['MDT', '-06:00'],
		['MST', '-07:00'],
		['PDT', '-07:00'],
		['PST', '-08:00'],
		['UT', '+00:00'],
		['GMT', '+00:00'],
	])('interprets %s as %s', (zone, offset) => {
		expect(parseSignedDate(`26 Sep 2026 14:32:00 ${zone}`)).toBe(
			`2026-09-26T14:32:00${offset}`,
		)
	})
	it.each('ABCDEFGHIKLMNOPQRSTUVWXYZ'.split(''))(
		'accepts military zone %s with unspecified local timezone',
		(zone) => {
			expect(
				parseSignedDate(`26 Sep 2026 14:32:00 ${zone.toLowerCase()}`),
			).toBe('2026-09-26T14:32:00-00:00')
		},
	)
})
